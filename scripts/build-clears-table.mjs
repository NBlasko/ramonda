/**
 * What every shorthand clears, written for the runtime merge.
 *
 *     node scripts/build-clears-table.mjs
 *     node scripts/build-clears-table.mjs --check     # fail if the committed table is stale
 *
 * ## Why the merge carries the whole table
 *
 * A module registers what the shorthands it writes clear. A PUBLISHED package is frozen, so what it
 * registers is the table of the release that built it. When CSS adds a longhand to a family, an old
 * package's `border: var(--x)` does not clear the new one, and a longhand written before it
 * survives where CSS would reset it. Measured in all three engines. The merge on the page is the
 * application's release, the newest one present, so the table has to live there.
 *
 * ## Why it is written this way
 *
 * One family per line, each shorthand listing only its DIRECT members: `border` names `border-top`,
 * and `border-top` names `border-top-color`. The merge follows the chain itself. Members that share
 * a prefix and a suffix are written once, in braces, the way a shell does:
 * `border_top_{color,style,width}`. Measured, gzipped: 3.7 KB for the full lists, 3.2 KB for direct
 * members, 2.7 KB with braces.
 *
 * **Two shorthands can cover each other** — `gap` and `grid-gap` are one property under two names.
 * A member is left out only when another member covers it, is not its twin, and does not cover the
 * family itself. Without the twin rule `mask-position` and `-webkit-mask-position` each dropped the
 * other from `mask`, and both were lost. The test expanding this table
 * back to the full lists is what holds that.
 *
 * Families with a member no key can spell are left out, exactly as the emitter leaves them out of
 * the table a module registers — see `clears` in `transform.ts`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadTs } from "./lib-load-ts.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "..", "packages", "css", "src");
const FILE = join(SRC, "clears.generated.ts");
const { SHORTHANDS } = await loadTs(join(SRC, "compiler", "keywords.generated.ts"));
const { writableProperty } = await loadTs(join(SRC, "compiler", "names.ts"));

const covers = (outer, inner) => (SHORTHANDS[outer] ?? []).includes(inner);

/** The members no other member already reaches, spelled the way a key spells them. */
function directMembers(family) {
  const members = SHORTHANDS[family];
  return members
    .filter(
      (one) =>
        !members.some((other) => other !== one && covers(other, one) && !covers(one, other) && !covers(other, family)),
    )
    .map(writableProperty);
}

/**
 * The fewest bytes for a list, greedily: the prefix and suffix, cut at `_`, that save the most, then
 * again on what is left. A group keeps the place of its first member.
 */
function braced(names) {
  const left = [...names];
  const out = [];
  while (left.length > 0) {
    let best;
    for (const one of left) {
      const parts = one.split("_");
      for (let head = 1; head < parts.length; head++)
        for (let tail = 0; head + tail < parts.length; tail++) {
          const prefix = `${parts.slice(0, head).join("_")}_`;
          const suffix = tail === 0 ? "" : `_${parts.slice(-tail).join("_")}`;
          const members = left.filter(
            (name) => name.startsWith(prefix) && name.endsWith(suffix) && name.length > prefix.length + suffix.length,
          );
          if (members.length < 2) continue;
          const written = `${prefix}{${members.map((name) => name.slice(prefix.length, name.length - suffix.length)).join(",")}}${suffix}`;
          const saved = members.join(" ").length - written.length;
          if (best === undefined || saved > best.saved) best = { members, written, saved };
        }
    }
    if (best === undefined || best.saved <= 0) {
      out.push(...left);
      break;
    }
    const at = Math.min(...best.members.map((name) => left.indexOf(name)));
    const before = left.slice(0, at).filter((name) => !best.members.includes(name));
    out.push(...before);
    for (const name of [...before, ...best.members]) left.splice(left.indexOf(name), 1);
    out.push(best.written);
  }
  return out;
}

const lines = [];
for (const family of Object.keys(SHORTHANDS).sort()) {
  const written = writableProperty(family);
  if (written === undefined || SHORTHANDS[family].some((one) => writableProperty(one) === undefined)) continue;
  lines.push(`${written}: ${braced(directMembers(family)).join(" ")}`);
}

const text = `// Generated by scripts/build-clears-table.mjs from keywords.generated.ts. Do not edit.
//
// What each shorthand clears, one family per line: the key's property, then its DIRECT members.
// \`a_{b,c}_d\` is \`a_b_d a_c_d\`. The merge follows a member that is itself a shorthand.

export const CLEARS_TABLE = \`
${lines.join("\n")}
\`;
`;

if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(FILE, "utf8");
  } catch {}
  if (committed !== text) {
    console.error("[clears] clears.generated.ts is stale — run node scripts/build-clears-table.mjs");
    process.exit(1);
  }
  console.log(`[clears] up to date — ${lines.length} families`);
} else {
  writeFileSync(FILE, text);
  console.log(`[clears] wrote ${lines.length} families`);
}
