#!/usr/bin/env node
/**
 * The DOM names `@ramonda/core` and `@ramonda/form` declare their types with, as the stand-ins
 * `ramonda-check` reads those types against — written to `packages/check/src/domStub.generated.ts`.
 *
 * Why there is a stub at all: `ramonda-check` builds its program with no lib, which keeps it fast — it
 * runs first in every build. One rule, `form-value-in-the-wrong-control`, asks a TYPE: whether a
 * control's `value` is a number or a day a form shows. Answering it through core's and the form's
 * declarations needs the names they mention — `HTMLInputElement`, `Event` — and the whole DOM lib is
 * 2.3 MB to parse for names whose contents the answer never reads. So each is declared as a stand-in:
 * DISTINCT, because an empty interface is `{}` and everything is assignable to it — measured, the
 * form then took a whole schema for a `File` and the answer collapsed to `any`.
 *
 * Derived, never written by hand: the names are what TypeScript cannot find in the built declarations
 * when the DOM lib is left out. So a name core starts using arrives here on the next run of this script,
 * and `--check` fails the gate until it has — it compares the file, and confirms that with the stub in
 * place nothing is left unfound.
 *
 *   node scripts/build-dom-names.mjs           writes the file
 *   node scripts/build-dom-names.mjs --check   fails when it is stale, or a name is still unfound
 *   SELFTEST=stale node scripts/build-dom-names.mjs --check
 *                                              must fail on a list missing a name: exits 0 when it does
 *
 * Needs `@ramonda/core` and `@ramonda/form` BUILT: it reads their `dist`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ts = createRequire(join(root, "packages/check/package.json"))("typescript");
const OUT = join(root, "packages/check/src/domStub.generated.ts");
const DECLARATIONS = [
  "packages/core/dist/index.d.ts",
  "packages/core/dist/jsx-runtime.d.ts",
  "packages/form/dist/index.d.ts",
].map((file) => join(root, file));

/** Without the DOM lib, with the rest of the language's own: what core's and the form's declarations name and cannot find. */
function unfound(extra) {
  const host = ts.createCompilerHost({});
  const stub = join(root, "__dom-stub__.d.ts");
  const read = host.readFile.bind(host);
  const source = host.getSourceFile.bind(host);
  host.readFile = (file) => (file === stub ? extra : read(file));
  host.getSourceFile = (file, language, onError, create) =>
    file === stub ? ts.createSourceFile(file, extra, language, true) : source(file, language, onError, create);
  const exists = host.fileExists.bind(host);
  host.fileExists = (file) => file === stub || exists(file);
  const program = ts.createProgram({
    rootNames: extra === undefined ? DECLARATIONS : [...DECLARATIONS, stub],
    options: { lib: ["lib.esnext.d.ts"], types: [], noEmit: true, strict: true, skipLibCheck: false },
    host,
  });
  const names = new Set();
  for (const diagnostic of ts.getPreEmitDiagnostics(program)) {
    // 2304: Cannot find name. 2552: … Did you mean …? Both name what is missing the same way.
    if (diagnostic.code !== 2304 && diagnostic.code !== 2552) continue;
    const name = /'([^']+)'/.exec(ts.flattenDiagnosticMessageText(diagnostic.messageText, " "))?.[1];
    if (name !== undefined) names.add(name);
  }
  return [...names].sort();
}

/** The stand-ins, one per name: an interface told apart from every other, and a value of it. */
function stubFor(names) {
  return names
    .map((name) => `interface ${name} { readonly "stub:${name}": never }\ndeclare var ${name}: ${name};`)
    .join("\n");
}

function fileFor(names) {
  return `// Generated by scripts/build-dom-names.mjs from the built declarations of @ramonda/core and
// @ramonda/form — do not edit; run the script. See it for why this exists.

/** The DOM names core's and the form's types mention, each as a distinct stand-in. */
export const DOM_STUB = \`${stubFor(names)}
\`;
`;
}

const names = unfound(undefined);
const check = process.argv.includes("--check");

if (!check) {
  writeFileSync(OUT, fileFor(names));
  console.log(`[dom-names] ${names.length} names → ${OUT}`);
  process.exit(0);
}

const written = (() => {
  try {
    return readFileSync(OUT, "utf8");
  } catch {
    return "";
  }
})();
const expected = process.env.SELFTEST === "stale" ? fileFor(names.slice(1)) : fileFor(names);
const stale = written !== expected;
const left = stale ? [] : unfound(stubFor(names));

if (process.env.SELFTEST === "stale") {
  if (stale) {
    console.log("[dom-names] self-test: a list missing a name is reported stale, as it must be");
    process.exit(0);
  }
  console.error("[dom-names] self-test FAILED: a list missing a name passed");
  process.exit(1);
}

if (stale) {
  console.error(
    `[dom-names] ${OUT} is stale: core's or the form's declarations name ${names.length} DOM names it does not match.\n` +
      "  Run: node scripts/build-dom-names.mjs",
  );
  process.exit(1);
}
if (left.length > 0) {
  console.error(`[dom-names] with the stub in place, still not found: ${left.join(", ")}`);
  process.exit(1);
}
console.log(`[dom-names] ${names.length} names, in step, and nothing left unfound`);
