import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { previousFrom, unionOfMap, writeOrCheck } from "./engine-facts.mjs";

/**
 * Writes `mediaValues.generated.ts`: what each media feature's value may be.
 *
 *   node scripts/css/build-media-values.mjs          # measure and write
 *   node scripts/css/build-media-values.mjs --check  # fail if this machine's engines know more
 *
 * A value a feature does not have is not an error to a browser. It makes the condition `unknown`,
 * which is neither true nor false — so `@media (prefers-color-scheme: drak)` is kept, parsed and
 * never applied, and `@media (min-width: 40)` the same: a bare number is not a length. The oracle is
 * that: a query an engine does not understand matches neither as itself nor negated.
 *
 * Asked of every feature: which WORDS it knows, from every keyword CSS has plus the words Media
 * Queries defines, and which KINDS of value — a length, a number, a ratio, a resolution. A word or
 * kind is kept if ANY engine knows it: this list ALLOWS, so it grows across engines and machines,
 * and a feature no engine knows is left out, so nothing is said about it.
 */

// `scripts/`, which every path below is written from.
const HERE = dirname(dirname(fileURLToPath(import.meta.url)));
const TAG = "build-media-values";
const check = process.argv.includes("--check");

const OUT = join(HERE, "..", "packages", "css", "src", "compiler", "mediaValues.generated.ts");
const pw = createRequire(join(HERE, "..", "apps", "playground-core", "package.json"))("@playwright/test");
const { KEYWORDS, MEDIA_FEATURES } = await import(
  join(HERE, "..", "packages", "css", "src", "compiler", "keywords.generated.ts")
);

/** Words Media Queries defines for its own features, which no property's keyword list carries. */
const MEDIA_WORDS = [
  "none",
  "hover",
  "fine",
  "coarse",
  "light",
  "dark",
  "portrait",
  "landscape",
  "reduce",
  "no-preference",
  "more",
  "less",
  "custom",
  "active",
  "srgb",
  "p3",
  "rec2020",
  "standard",
  "high",
  "browser",
  "fullscreen",
  "minimal-ui",
  "standalone",
  "picture-in-picture",
  "window-controls-overlay",
  "inverted",
  "interlace",
  "progressive",
  "slow",
  "fast",
  "paged",
  "optional-paged",
  "scroll",
  "enabled",
  "initial-only",
  "opaque",
];
const candidates = [
  ...new Set([...MEDIA_WORDS, ...Object.values(KEYWORDS).flatMap((list) => String(list).split(" "))]),
].filter((word) => /^[a-z][a-z0-9-]*$/.test(word));

/**
 * One value of each kind a media feature may take. `0` is asked apart, since it is a length too; the
 * number is `1`, because `grid` takes only `0` and `1` and was missed when it was asked with `2`.
 */
const KINDS = { length: "40px", zero: "0", number: "1", ratio: "16/9", resolution: "2dppx" };

const perEngine = [];
for (const engine of ["chromium", "firefox", "webkit"]) {
  let browser;
  try {
    browser = await pw[engine].launch();
    const tab = await browser.newPage();
    await tab.setContent("<!doctype html><html><head></head><body></body></html>");
    const found = await tab.evaluate(
      ({ features, words, kinds }) => {
        const known = (query) => matchMedia(query).matches || matchMedia(`not ${query}`).matches;
        const out = { words: {}, kinds: {} };
        for (const feature of features) {
          const w = words.filter((word) => known(`(${feature}: ${word})`));
          const k = Object.entries(kinds)
            .filter(([, value]) => known(`(${feature}: ${value})`))
            .map(([kind]) => kind);
          if (w.length > 0 || k.length > 0) {
            out.words[feature] = w;
            out.kinds[feature] = k;
          }
        }
        return out;
      },
      { features: MEDIA_FEATURES, words: candidates, kinds: KINDS },
    );
    perEngine.push([engine, found]);
  } catch (error) {
    console.error(`[${TAG}] ${engine} would not launch, so the table would be short: ${String(error).slice(0, 90)}`);
    console.error(`[${TAG}] run \`npx playwright install ${engine}\` in apps/playground-core, then this again.`);
    process.exit(1);
  } finally {
    await browser?.close();
  }
}

/** Any engine knowing a word or kind keeps it, and every machine's answer is kept beside it. */
let words = {};
let kinds = {};
for (const [, found] of perEngine) {
  words = unionOfMap(words, found.words);
  kinds = unionOfMap(kinds, found.kinds);
}
words = unionOfMap(
  previousFrom(OUT, /MEDIA_WORDS: Readonly<Record<string, readonly string\[\]>> = (\{[\s\S]*?\});/, {}),
  words,
);
kinds = unionOfMap(
  previousFrom(OUT, /MEDIA_KINDS: Readonly<Record<string, readonly string\[\]>> = (\{[\s\S]*?\});/, {}),
  kinds,
);

const contents =
  `// Generated by scripts/css/${TAG}.mjs from Chromium, Firefox and WebKit, MEASURED\n` +
  `// rather than read: each browser is launched and asked which media queries it understands. No\n` +
  `// engine source is used. See THIRD-PARTY.md. Do not edit.\n` +
  "\n" +
  "/** The words each media feature's value may be, in any engine measured. */\n" +
  `export const MEDIA_WORDS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(words)};\n` +
  "\n" +
  "/** The kinds of value each feature takes: `length`, `zero`, `number`, `ratio`, `resolution`. */\n" +
  `export const MEDIA_KINDS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(kinds)};\n`;

const wrote = writeOrCheck(OUT, contents, TAG, check);
console.log(
  `[${TAG}] ${Object.keys(kinds).length} features, ${candidates.length} words asked${wrote ? " — written" : ""}`,
);
