/**
 * Writes the rule tables on the check reference page, from the rules themselves.
 *
 * ## Why generated
 *
 * The page carried two tables of rules typed by hand, and the day a branch added nine of them the
 * tables were nine rows short — silently, because nothing connected the two. A reference that is
 * quietly incomplete is worse than one that says so, because a reader trusts it: a rule missing
 * from the page is a rule nobody knows they are being judged by.
 *
 * So the rows come from `ruleCatalogue()`, which reads them off the rules. Adding a rule adds its
 * row; changing what a rule reports changes the row it appears in; and neither can be forgotten,
 * because the build compares this file's output against what is committed.
 *
 *   node scripts/build-rule-tables.mjs          # write them
 *   node scripts/build-rule-tables.mjs --check  # fail if they are out of date (for CI)
 *
 * ## It writes the issue-type list on the API page too
 *
 * Same argument, arrived at from the other direction: that list is a paragraph naming every rule's
 * issue shape, and it was maintained by hand. Every rule added meant editing it, every BRANCH that
 * added a rule collided with every other branch there, and the only thing catching a miss was
 * `check-api-coverage.mjs` failing the build afterwards.
 *
 * The names are read from what `@ramonda/check` actually exports, rather than derived from rule ids
 * — a derivation would need the same list of naming exceptions the surface test keeps, which is one
 * more copy of a thing that must agree.
 *
 * ## Why the markers are link definitions
 *
 * A generated region needs a boundary the renderer does not show. Markdown here is rendered with
 * `html: false`, so an HTML comment is ESCAPED and arrives at the reader as `<!-- … -->` — measured,
 * not assumed. A link reference definition is consumed by the parser instead and produces no
 * output at all, which is the property this needs.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ruleCatalogue } from "@ramonda/check";

const here = dirname(fileURLToPath(import.meta.url));
const content = join(here, "..", "content", "reference");
const page = join(content, "check.md");
const diagnostics = join(content, "diagnostics.md");
const check = process.argv.includes("--check");

/**
 * The generated region's bounds, and where the "do not edit this by hand" reminder lives.
 *
 * A link-reference definition renders nothing, and it may carry a title — so the reminder sits in the
 * file, where somebody about to edit the table sees it, and not on the page, where a reader was being
 * told how the docs are built. The blocks used to carry it as a visible italic line.
 *
 * The bounds are matched by these exact strings, so changing one means rewriting the pages that
 * already carry the old spelling in the same commit.
 */
const START = '[rules:start]: # "generated by scripts/build-rule-tables.mjs — edit the rule, not this"';
const END = "[rules:end]: #";

const api = join(content, "api.md");
const ISSUES_START = '[issues:start]: # "generated by scripts/build-rule-tables.mjs — edit the rule, not this"';
const ISSUES_END = "[issues:end]: #";

/**
 * The row for one rule.
 *
 * The id is the first column and not a prose title, because the id is the thing a reader uses:
 * it is the key in `findings`, and it is what the command prints when a rule is named. A title
 * would be a second name for the same rule, written here and nowhere else — which is the drift
 * this script exists to end.
 *
 * It LINKS to the rule's own page, which `build-content.mjs` generates from the same catalogue. The
 * table answers "what does this tool check"; the page answers "what is this one, and what do I write
 * instead" — and only the second is something a search engine can rank, which is why a rule living
 * only in a row is a rule nobody arrives at.
 */
function row(rule) {
  // A rule may answer several codes — `duplicate-decorators` answers four — so every one is linked.
  const codes = rule.alsoReportedAs ?? [];
  const also =
    codes.length > 0
      ? ` — also ${codes.map((code) => `[\`${code}\`](/reference/diagnostics/${code.toLowerCase()})`).join(", ")}`
      : "";
  return `| [\`${rule.id}\`](/rules/${rule.id}) | ${rule.reportedWhen}${also} |`;
}

function table(rules) {
  return ["| rule | reported when |", "|---|---|", ...rules.map(row)].join("\n");
}

const rules = ruleCatalogue();
const errors = rules.filter((rule) => rule.severity === "error");
const warnings = rules.filter((rule) => rule.severity === "warn");

/**
 * A code named by a rule has to be a code the diagnostics page documents.
 *
 * The link is generated, so a typo would render as a link to a page section that does not exist —
 * which looks fine in a build and is broken for the reader. Two lists that have to agree is the
 * shape this whole script is about, so it checks this one too rather than only the one it writes.
 */
const documented = readFileSync(diagnostics, "utf8");
const missing = rules
  .flatMap((rule) => (rule.alsoReportedAs ?? []).map((code) => ({ rule, code })))
  .filter(({ code }) => !documented.includes(code))
  .map(({ rule, code }) => `${rule.id} names ${code}`);
if (missing.length > 0) {
  console.error(
    `[rules] ${missing.length} rule(s) name a diagnostic the reference does not document:\n` +
      missing.map((line) => `        ${line}`).join("\n"),
  );
  process.exit(1);
}

/**
 * Split only when there is something to split.
 *
 * Every rule fails the run today, so emitting both labels produced "**Warnings.** These print and
 * the run still passes. 0 of them." above a table with no rows — a heading over nothing, which
 * reads as a list that failed to render rather than as a fact. The split comes back on its own the
 * day a rule warns again.
 */
const region = [
  START,
  "",
  ...(warnings.length > 0
    ? [
        `**Errors.** These fail the run. ${errors.length} of them.`,
        "",
        table(errors),
        "",
        `**Warnings.** These print and the run still passes. ${warnings.length} of them.`,
        "",
        table(warnings),
      ]
    : [`**Every one of them fails the run.** ${errors.length} rules.`, "", table(errors)]),
  "",
  END,
].join("\n");

const existing = readFileSync(page, "utf8");
const from = existing.indexOf(START);
const to = existing.indexOf(END);
if (from === -1 || to === -1 || to < from) {
  console.error(
    `[rules] check.md has no generated region.\n` +
      `        It is bounded by the link definitions ${START} and ${END};\n` +
      `        without both, this script has nowhere to write and would silently do nothing.`,
  );
  process.exit(1);
}

/**
 * Replaces one generated region, or says clearly why it cannot.
 *
 * Shared by the two pages this writes, because the failure that matters is the same on both: a
 * missing marker means the script has nowhere to write and would otherwise do nothing at all,
 * quietly, which is exactly the drift it exists to end.
 */
function replaceRegion(file, startMarker, endMarker, body) {
  const text = readFileSync(file, "utf8");
  const at = text.indexOf(startMarker);
  const until = text.indexOf(endMarker);
  if (at === -1 || until === -1 || until < at) {
    console.error(
      `[rules] ${file} has no generated region.\n` +
        `        It is bounded by the link definitions ${startMarker} and ${endMarker};\n` +
        `        without both, this script has nowhere to write and would silently do nothing.`,
    );
    process.exit(1);
  }
  return { text, updated: text.slice(0, at) + body + text.slice(until + endMarker.length) };
}

/**
 * Every issue shape the package publishes, read from what it actually exports.
 *
 * The source of truth is `src/rules/index.ts`, for two reasons that both matter. It is not the rule
 * IDS, because deriving `ArrowFieldIssue` from `arrow-fields` needs the naming exceptions the
 * surface test keeps and a second copy of those is what this script exists to avoid. And it is not
 * `src/index.ts`, because that also publishes the GRAPH checks' shapes — `ContextIssue` is real and
 * public and is not any rule's, so a sentence beginning "every rule publishes" must not name it.
 */
function issueTypes() {
  const source = readFileSync(join(here, "..", "..", "..", "packages", "check", "src", "rules", "index.ts"), "utf8");
  /**
   * Both spellings of a type export, because both are written and the first version read only one.
   *
   * `export { rule, type RuleIssue }` is the form every rule uses today; `export type { RuleIssue }`
   * is the form somebody will use tomorrow. Found by planting a name in the second form and watching
   * `--check` stay green — which is the whole reason to plant one.
   */
  const names = [
    ...[...source.matchAll(/\btype (\w+Issue)\b/g)].map((match) => match[1]),
    ...[...source.matchAll(/\btype \{([^}]*)\}/g)].flatMap((match) => match[1].match(/\w+Issue/g) ?? []),
  ];
  return [...new Set(names)].sort();
}

/** The paragraph, wrapped so the file stays readable in a diff. */
function paragraph(names) {
  const words = `Every rule publishes its own issue shape, named for the rule: ${names
    .map((name) => `\`${name}\``)
    .join(", ")}.`.split(" ");
  const lines = [];
  let line = "";
  for (const word of words) {
    if (line.length > 0 && `${line} ${word}`.length > 100) {
      lines.push(line);
      line = word;
    } else line = line.length === 0 ? word : `${line} ${word}`;
  }
  if (line.length > 0) lines.push(line);
  return lines.join("\n");
}

/**
 * No early exit when this page is already right.
 *
 * There used to be a `process.exit(0)` here, and moving the API page's block below it made that
 * exit skip the second page entirely — a planted name went unreported and the run stayed green.
 * Caught by planting one, which is the only reason to plant one. Two pages means the script may
 * only finish once, at the end.
 */
const updated = existing.slice(0, from) + region + existing.slice(to + END.length);
if (updated !== existing) {
  if (check) {
    console.error(
      "[rules] the rule tables in reference/check.md are out of date\n" +
        "        run `node scripts/build-rule-tables.mjs` and commit the result.",
    );
    process.exit(1);
  }
  writeFileSync(page, updated);
  console.log(`[rules] reference/check.md — ${errors.length} errors, ${warnings.length} warnings`);
}

const issues = issueTypes();
const issueRegion = [ISSUES_START, "", paragraph(issues), "", ISSUES_END].join("\n");

const apiPage = replaceRegion(api, ISSUES_START, ISSUES_END, issueRegion);
if (apiPage.updated !== apiPage.text) {
  if (check) {
    console.error(
      "[rules] the issue-type list in reference/api.md is out of date\n" +
        "        run `node scripts/build-rule-tables.mjs` and commit the result.",
    );
    process.exit(1);
  }
  writeFileSync(api, apiPage.updated);
  console.log(`[rules] reference/api.md — ${issues.length} issue types`);
}

if (check) console.log(`[rules] up to date — ${rules.length} rules, ${issues.length} issue types`);
