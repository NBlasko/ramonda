import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Maps every lazily-imported module to the chunk URL the browser will fetch.
 *
 * This is the piece nothing at runtime can know. The server resolves
 * `() => import("./pages/concepts-state")` inside ITS module graph; the browser
 * fetches `/assets/chunk-A1B2C3.js`. Only the bundler knows the correspondence,
 * and only after it has hashed the output — so the mapping comes from the build,
 * and `AsyncLoad`'s `preload` prop has to be handed it.
 *
 * esbuild's `--metafile` records which inputs went into each output chunk. Two
 * kinds matter here: a demo under `demos/lazy/`, and a page under
 * `generated/pages/`.
 */
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const meta = JSON.parse(readFileSync(join(root, ".build", "meta.json"), "utf8"));

/** Demo module name → chunk URL. */
const preloads = {};
/** Route path → that page's content chunk. */
const pagePreloads = {};

/** `concepts-state.ts` → `/concepts/state`; `index.ts` → `/`. */
function routePathFor(moduleFile) {
  const name = moduleFile.replace(/\.tsx?$/, "");
  return name === "index" ? "/" : "/" + name.split("-").join("/");
}

const toPosix = (value) => value.split("\\").join("/");

for (const [outputPath, output] of Object.entries(meta.outputs)) {
  // NOT `if (output.entryPoint)`. esbuild marks a dynamically imported chunk as
  // an entry point too — which is correct, it IS an entry into the graph — so
  // that check skips exactly the chunks we are looking for. Only the page's own
  // entry is excluded, and it is excluded by name.
  if (output.entryPoint === "src/entry-client.tsx") continue;

  const url = "/" + toPosix(relative(join(root, "dist"), join(root, outputPath)));

  for (const input of Object.keys(output.inputs)) {
    const rel = toPosix(relative(root, join(root, input)));
    const file = rel.split("/").pop();

    if (rel.includes("src/demos/lazy/")) {
      preloads[file.replace(/\.tsx?$/, "")] = url;
    } else if (rel.includes("src/generated/pages/")) {
      pagePreloads[routePathFor(file)] = url;
    }
  }
}

writeFileSync(
  join(root, "src", "generated", "preloads.ts"),
  `// GENERATED by scripts/build-manifest.mjs — do not edit.\n` +
    `// Lazy module → the chunk URL the browser fetches for it.\n\n` +
    `export const preloads: Record<string, string> = ${JSON.stringify(preloads, null, 2)};\n\n` +
    `/** Route path → that page's content chunk. */\n` +
    `export const pagePreloads: Record<string, string | undefined> = ${JSON.stringify(pagePreloads, null, 2)};\n`,
);

console.log(
  `[docs] preload map: ${Object.keys(preloads).length} demo chunk(s), ` +
    `${Object.keys(pagePreloads).length} page chunk(s)`,
);
